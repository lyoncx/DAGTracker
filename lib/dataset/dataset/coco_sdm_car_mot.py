#!/usr/bin/env python3
"""
SDM-Car-MOT dataset class for HiEUM training.

- Resolution: 1920x1080 (different from SAT-MTB 512x512)
- Uses annotations generated by prepare_sdm_car_mot_dataset.py
"""

from __future__ import absolute_import
from __future__ import division
from __future__ import print_function

import pycocotools.coco as coco
from pycocotools.cocoeval import COCOeval
import numpy as np
import json
import os

import torch.utils.data as data
import torch
import cv2
from lib.utils1.image import flip, color_aug
from lib.utils1.image import get_affine_transform, affine_transform
from lib.utils1.image import gaussian_radius, draw_umich_gaussian, draw_msra_gaussian
from lib.utils1.image import draw_dense_reg
import math
from lib.utils1.opts import opts

from lib.utils1.augmentations import Augmentation

from collections import defaultdict


class COCO_sdm_car_mot(data.Dataset):
    opt = opts().parse()
    num_classes = 1
    # SDM-Car-MOT: 1920x1080 resolution (original)
    default_resolution = [1080, 1920]
    # 统计了 100 张随机图像: Mean=[0.16,0.16,0.16], Std=[0.28,0.28,0.25]
    mean = np.array([0.16, 0.16, 0.16],
                   dtype=np.float32).reshape(1, 1, 3)
    std  = np.array([0.28, 0.28, 0.25],
                   dtype=np.float32).reshape(1, 1, 3)

    def __init__(self, opt, split):
        super(COCO_sdm_car_mot, self).__init__()
        self._eig_val = np.array([0.2141788, 0.01817699, 0.00341571],
                                 dtype=np.float32)
        self._eig_vec = np.array([
            [-0.58752847, -0.69563484, 0.41340352],
            [-0.5832747, 0.00994535, -0.81221408],
            [-0.56089297, 0.71832671, 0.41158938]
        ], dtype=np.float32)

        self.img_dir0 = self.opt.data_dir
        self.img_dir = self.opt.data_dir

        # Use 1920x1080 resolution (original)
        if split == 'train':
            self.resolution = [1080, 1920]
            self.resolution_ori = [1080, 1920]
            self.annot_path = os.path.join(
                self.img_dir0, 'annotations',
                'train.json').format(split)
        else:
            self.resolution = [1080, 1920]
            self.annot_path = os.path.join(
                self.img_dir0, 'annotations',
                'test.json').format(split)

        self.down_ratio = opt.down_ratio
        self.max_objs = opt.K
        self.seqLen = opt.seqLen

        self.class_name = ['__background__', 'car']
        self._valid_ids = [0]
        self.cat_ids = {v: i for i, v in enumerate(self._valid_ids)}

        self.split = split
        self.opt = opt

        print('==> initializing SDM-Car-MOT {} data.'.format(split))
        print(f'    Resolution: {self.resolution[0]}x{self.resolution[1]}')
        self.coco = coco.COCO(self.annot_path)
        self.images = self.coco.getImgIds()
        img_root = os.path.join(self.img_dir, self.split)

        self.video_to_images = defaultdict(dict)
        self.video_lens = {}
        valid_image_ids = []
        missing_images = 0
        missing_examples = []

        for image in self.coco.dataset['images']:
            file_name = image['file_name']
            path_parts = os.path.normpath(file_name).split(os.sep)
            file_basename = os.path.basename(file_name)
            video_frame_id = int(os.path.splitext(file_basename)[0])
            # file_name 格式为 '1-1/img1/000001.jpg'，video_id 是第一个部分 '1-1'
            video_id = path_parts[0]
            img_path = os.path.join(img_root, file_name)

            if not os.path.exists(img_path):
                missing_images += 1
                if len(missing_examples) < 5:
                    missing_examples.append(os.path.join(self.split, file_name))
                continue

            image['video_id'] = video_id
            image['video_frame_id'] = video_frame_id
            self.video_to_images[video_id][video_frame_id] = image
            valid_image_ids.append(image['id'])

        if missing_images > 0:
            print(f"[Warning] {self.split} split: skipped {missing_images} frames missing under {img_root}.")
            if missing_examples:
                print("Examples of missing files:", missing_examples)

        valid_id_set = set(valid_image_ids)
        self.images = [img_id for img_id in self.images if img_id in valid_id_set]
        self.num_samples = len(self.images)

        for video_id, frames in self.video_to_images.items():
            frame_ids = frames.keys()
            video_len = max(frame_ids)
            self.video_lens[video_id] = video_len

        if split == 'train':
            self.aug = Augmentation()
        else:
            self.aug = None

    def _to_float(self, x):
        return float("{:.2f}".format(x))

    def convert_eval_format(self, all_bboxes):
        detections = []
        for image_id in all_bboxes:
            for cls_ind in all_bboxes[image_id]:
                category_id = self._valid_ids[cls_ind - 1]
                for bbox in all_bboxes[image_id][cls_ind]:
                    bbox[2] -= bbox[0]
                    bbox[3] -= bbox[1]
                    score = bbox[4]
                    bbox_out = list(map(self._to_float, bbox[0:4]))
                    detection = {
                        "image_id": int(image_id),
                        "category_id": int(category_id),
                        "bbox": bbox_out,
                        "score": float("{:.2}".format(score))
                    }
                    if len(bbox) > 5:
                        extreme_points = list(map(self._to_float, bbox[5:13]))
                        detection["extreme_points"] = extreme_points
                    detections.append(detection)
        return detections

    def __len__(self):
        return self.num_samples

    def save_results(self, results, save_dir, time_str):
        json.dump(self.convert_eval_format(results),
                  open('{}/results_{}.json'.format(save_dir, time_str), 'w'))
        print('{}/results_{}.json'.format(save_dir, time_str))

    def run_eval(self, results, save_dir, time_str):
        self.save_results(results, save_dir, time_str)
        coco_dets = self.coco.loadRes('{}/results_{}.json'.format(save_dir, time_str))
        coco_eval = COCOeval(self.coco, coco_dets, "bbox")
        coco_eval.evaluate()
        coco_eval.accumulate()
        coco_eval.summarize()
        stats = coco_eval.stats
        precisions = coco_eval.eval['precision']
        return stats, precisions

    def run_eval_just(self, save_dir, time_str, iouth):
        coco_dets = self.coco.loadRes('{}/{}'.format(save_dir, time_str))
        coco_eval = COCOeval(self.coco, coco_dets, "bbox", iouth=iouth)
        coco_eval.evaluate()
        coco_eval.accumulate()
        coco_eval.summarize()
        stats_5 = coco_eval.stats
        precisions = coco_eval.eval['precision']
        return stats_5, precisions

    def _coco_box_to_bbox(self, box):
        box[2] = box[0] + box[2]
        box[3] = box[1] + box[3]
        bbox = np.array(box, dtype=np.float32)
        return bbox

    def _get_border(self, border, size):
        i = 1
        while size - border // i <= border // i:
            i *= 2
        return border // i
